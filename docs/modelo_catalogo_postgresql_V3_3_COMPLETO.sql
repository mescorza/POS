    texto_busqueda=EXCLUDED.texto_busqueda,
    marcas_vehiculo=EXCLUDED.marcas_vehiculo,
    modelos_vehiculo=EXCLUDED.modelos_vehiculo,
    codigos_referencia=EXCLUDED.codigos_referencia,
