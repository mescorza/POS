-- Vista de control: deben aparecer 64 filas con existe_en_schema = true
CREATE OR REPLACE VIEW vw_modelo_control_tablas AS
SELECT
    e.table_name,
    EXISTS (
        SELECT 1
        FROM information_schema.tables t
        WHERE t.table_schema = 'catalogo'
          AND t.table_name = e.table_name
          AND t.table_type = 'BASE TABLE'
    ) AS existe_en_schema
FROM modelo_tabla_esperada e;

-- Validación estricta. Lanza excepción si falta una tabla funcional del modelo.
DO $$
DECLARE
    v_faltantes TEXT;
    v_cantidad INTEGER;
BEGIN
    SELECT COUNT(*)
      INTO v_cantidad
      FROM modelo_tabla_esperada;

    IF v_cantidad <> 64 THEN
        RAISE EXCEPTION 'Inventario V3.2 inválido: se esperaban 64 tablas y hay %', v_cantidad;
    END IF;

    SELECT string_agg(table_name, ', ' ORDER BY table_name)
      INTO v_faltantes
      FROM vw_modelo_control_tablas
     WHERE existe_en_schema = FALSE;

    IF v_faltantes IS NOT NULL THEN
        RAISE EXCEPTION 'Modelo V3.2 incompleto. Faltan tablas: %', v_faltantes;
    END IF;
END $$;

