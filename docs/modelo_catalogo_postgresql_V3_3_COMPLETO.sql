INSERT INTO sku_busqueda
(sku_id, texto_busqueda, marcas_vehiculo, modelos_vehiculo,
 codigos_referencia, marca_repuesto, categoria, motores,
 pais_origen, nivel_calidad_id, search_vector)
SELECT
    s.sku_id,
    concat_ws(' ',
        s.sku, s.mpn, p.nombre, m.nombre,
        string_agg(DISTINCT rr.codigo, ' '),
        string_agg(DISTINCT vm.nombre, ' '),
        string_agg(DISTINCT vmo.nombre, ' '),
        string_agg(DISTINCT mot.codigo_motor, ' ')
    ) AS texto_busqueda,
    string_agg(DISTINCT vm.nombre, ', '),
    string_agg(DISTINCT vmo.nombre, ', '),
    string_agg(DISTINCT rr.codigo, ', '),
    m.nombre,
    NULL,
    string_agg(DISTINCT mot.codigo_motor, ', '),
    po.nombre,
    sc.nivel_calidad_id,
    to_tsvector('simple',
      concat_ws(' ', s.sku, s.mpn, p.nombre, m.nombre,
        string_agg(DISTINCT rr.codigo, ' '),
        string_agg(DISTINCT vm.nombre, ' '),
        string_agg(DISTINCT vmo.nombre, ' '),
        string_agg(DISTINCT mot.codigo_motor, ' ')
      )
    )
FROM sku s
JOIN producto p ON p.producto_id=s.producto_id
LEFT JOIN marca m ON m.marca_id=p.marca_id
LEFT JOIN sku_referencia sr ON sr.sku_id=s.sku_id
LEFT JOIN referencia_repuesto rr ON rr.referencia_repuesto_id=sr.referencia_repuesto_id
LEFT JOIN sku_aplicacion_vehiculo sav ON sav.sku_id=s.sku_id
LEFT JOIN vehiculo_configuracion vc ON vc.vehiculo_configuracion_id=sav.vehiculo_configuracion_id
LEFT JOIN vehiculo_generacion vg ON vg.vehiculo_generacion_id=vc.vehiculo_generacion_id
LEFT JOIN vehiculo_modelo vmo ON vmo.vehiculo_modelo_id=vg.vehiculo_modelo_id
LEFT JOIN vehiculo_marca vm ON vm.vehiculo_marca_id=vmo.vehiculo_marca_id
LEFT JOIN vehiculo_motor mot ON mot.vehiculo_motor_id=vc.vehiculo_motor_id
LEFT JOIN sku_origen so ON so.sku_id=s.sku_id
LEFT JOIN pais po ON po.pais_id=so.pais_origen_id
LEFT JOIN sku_clasificacion_calidad sc ON sc.sku_id=s.sku_id
WHERE s.sku_id=7001
GROUP BY s.sku_id,s.sku,s.mpn,p.nombre,m.nombre,po.nombre,sc.nivel_calidad_id
