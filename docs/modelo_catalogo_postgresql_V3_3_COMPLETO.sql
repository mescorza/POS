-- 4. ATRIBUTOS TECNICOS
-- ============================================================

CREATE TABLE grupo_atributo (
    grupo_atributo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    orden INTEGER NULL
);

CREATE TABLE atributo (
    atributo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_atributo_id BIGINT NULL REFERENCES grupo_atributo(grupo_atributo_id),
    codigo VARCHAR(80) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    tipo_dato VARCHAR(30) NOT NULL,
    nivel_aplicacion VARCHAR(20) NOT NULL DEFAULT 'AMBOS' CHECK (nivel_aplicacion IN ('PRODUCTO','SKU','AMBOS')),
    unidad_medida_id BIGINT NULL REFERENCES unidad_medida(unidad_medida_id),
    permite_multiple BOOLEAN NOT NULL DEFAULT FALSE,
    es_filtrable BOOLEAN NOT NULL DEFAULT FALSE,
    es_comparable BOOLEAN NOT NULL DEFAULT FALSE,
    es_busqueda BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE atributo_opcion (
    atributo_opcion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atributo_id BIGINT NOT NULL REFERENCES atributo(atributo_id),
    codigo VARCHAR(80) NULL,
    nombre VARCHAR(160) NOT NULL,
    orden INTEGER NULL
);

CREATE TABLE categoria_atributo (
    categoria_id BIGINT NOT NULL REFERENCES categoria(categoria_id),
    atributo_id BIGINT NOT NULL REFERENCES atributo(atributo_id),
    obligatorio BOOLEAN NOT NULL DEFAULT FALSE,
    orden INTEGER NULL,
    PRIMARY KEY (categoria_id, atributo_id)
);

CREATE TABLE producto_atributo (
    producto_atributo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL REFERENCES producto(producto_id),
    sku_id BIGINT NULL REFERENCES sku(sku_id),
    atributo_id BIGINT NOT NULL REFERENCES atributo(atributo_id),
    atributo_opcion_id BIGINT NULL REFERENCES atributo_opcion(atributo_opcion_id),
    valor_texto TEXT NULL,
    valor_numero NUMERIC(24,8) NULL,
    valor_boolean BOOLEAN NULL,
    valor_fecha DATE NULL,
    unidad_medida_id BIGINT NULL REFERENCES unidad_medida(unidad_medida_id)
);

CREATE INDEX idx_producto_atributo_prod ON producto_atributo(producto_id);
CREATE INDEX idx_producto_atributo_sku ON producto_atributo(sku_id);
CREATE INDEX idx_producto_atributo_attr ON producto_atributo(atributo_id);


-- V2: atributos técnicos/comerciales específicos de SKU
CREATE TABLE sku_atributo (
    sku_atributo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_id BIGINT NOT NULL REFERENCES sku(sku_id),
    atributo_id BIGINT NOT NULL REFERENCES atributo(atributo_id),
    atributo_opcion_id BIGINT NULL REFERENCES atributo_opcion(atributo_opcion_id),
    valor_texto TEXT NULL,
    valor_numero NUMERIC(24,8) NULL,
    valor_boolean BOOLEAN NULL,
    valor_fecha DATE NULL,
    unidad_medida_id BIGINT NULL REFERENCES unidad_medida(unidad_medida_id)
);
CREATE INDEX idx_sku_atributo_sku ON sku_atributo(sku_id);
CREATE INDEX idx_sku_atributo_attr ON sku_atributo(atributo_id);




