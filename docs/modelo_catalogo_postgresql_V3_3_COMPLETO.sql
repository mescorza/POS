-- 1. TABLAS MAESTRAS
-- ============================================================

CREATE TABLE producto_tipo (
    producto_tipo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT NULL,
    estado VARCHAR(20) NOT NULL
);


CREATE TABLE fabricante (
    fabricante_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(180) NOT NULL,
    pais_codigo CHAR(2) NULL,
    sitio_web VARCHAR(500) NULL,
    estado VARCHAR(20) NOT NULL
);

CREATE TABLE marca (
    marca_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fabricante_id BIGINT NULL REFERENCES fabricante(fabricante_id),
    nombre VARCHAR(150) NOT NULL,
    slug VARCHAR(180) NULL UNIQUE,
    estado VARCHAR(20) NOT NULL
);

CREATE TABLE unidad_medida (
    unidad_medida_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(80) NOT NULL,
    simbolo VARCHAR(20) NULL,
    tipo_magnitud VARCHAR(50) NULL
);

CREATE TABLE producto (
    producto_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_padre_id BIGINT NULL,
    producto_tipo_id BIGINT NOT NULL REFERENCES producto_tipo(producto_tipo_id),
    marca_id BIGINT NULL REFERENCES marca(marca_id),
    nombre VARCHAR(250) NOT NULL,
    nombre_corto VARCHAR(120) NULL,
    codigo_modelo VARCHAR(100) NULL,
    descripcion TEXT NULL,
    descripcion_larga TEXT NULL,
    nivel SMALLINT NULL,
    es_hoja BOOLEAN NOT NULL DEFAULT TRUE,
    es_vendible BOOLEAN NOT NULL DEFAULT TRUE,
    es_visible BOOLEAN NOT NULL DEFAULT TRUE,
    estado VARCHAR(30) NOT NULL,
    fecha_lanzamiento DATE NULL,
    fecha_inicio TIMESTAMP NULL,
    fecha_fin TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_producto_padre
        FOREIGN KEY (producto_padre_id) REFERENCES producto(producto_id)
);

CREATE INDEX idx_producto_padre ON producto(producto_padre_id);
CREATE INDEX idx_producto_marca ON producto(marca_id);
CREATE INDEX idx_producto_tipo ON producto(producto_tipo_id);

CREATE TABLE sku (
    sku_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL REFERENCES producto(producto_id),
    sku VARCHAR(80) NOT NULL UNIQUE,
    mpn VARCHAR(120) NULL,
    ean VARCHAR(20) NULL,
    upc VARCHAR(20) NULL,
    isbn VARCHAR(20) NULL,
    codigo_proveedor VARCHAR(120) NULL,
    descripcion VARCHAR(300) NULL,
    estado VARCHAR(30) NOT NULL,
    es_vendible BOOLEAN NOT NULL DEFAULT TRUE,
    es_inventariable BOOLEAN NOT NULL DEFAULT TRUE,
    es_serializable BOOLEAN NOT NULL DEFAULT FALSE,
    peso NUMERIC(14,4) NULL,
    alto NUMERIC(14,4) NULL,
    ancho NUMERIC(14,4) NULL,
    profundidad NUMERIC(14,4) NULL,
    unidad_medida_id BIGINT NULL REFERENCES unidad_medida(unidad_medida_id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_sku_producto ON sku(producto_id);
CREATE INDEX idx_sku_mpn ON sku(mpn);



