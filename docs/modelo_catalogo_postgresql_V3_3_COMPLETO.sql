CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE pais (
    pais_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_iso2 CHAR(2) NOT NULL UNIQUE,
    codigo_iso3 CHAR(3) NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    region VARCHAR(80) NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
);

CREATE TABLE grupo_automotriz (
    grupo_automotriz_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(60) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    pais_origen_id BIGINT NULL REFERENCES pais(pais_id),
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
);

ALTER TABLE vehiculo_marca
    ADD COLUMN IF NOT EXISTS grupo_automotriz_id BIGINT NULL;

ALTER TABLE vehiculo_marca
    ADD CONSTRAINT fk_vehiculo_marca_grupo
    FOREIGN KEY (grupo_automotriz_id) REFERENCES grupo_automotriz(grupo_automotriz_id);

CREATE INDEX IF NOT EXISTS idx_vehiculo_marca_grupo
    ON vehiculo_marca(grupo_automotriz_id);

CREATE TABLE plataforma_vehiculo (
    plataforma_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_automotriz_id BIGINT NULL REFERENCES grupo_automotriz(grupo_automotriz_id),
    codigo VARCHAR(80) NOT NULL UNIQUE,
    nombre VARCHAR(150) NULL,
    agno_desde SMALLINT NULL,
    agno_hasta SMALLINT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_plataforma_agno CHECK (
        agno_desde IS NULL OR agno_hasta IS NULL OR agno_hasta >= agno_desde
    )
);

CREATE TABLE vehiculo_generacion_plataforma (
    vehiculo_generacion_id BIGINT NOT NULL REFERENCES vehiculo_generacion(vehiculo_generacion_id),
    plataforma_id BIGINT NOT NULL REFERENCES plataforma_vehiculo(plataforma_id),
    es_principal BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (vehiculo_generacion_id, plataforma_id)
);

CREATE TABLE familia_motor (
    familia_motor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_automotriz_id BIGINT NULL REFERENCES grupo_automotriz(grupo_automotriz_id),
    fabricante_id BIGINT NULL REFERENCES fabricante(fabricante_id),
    codigo VARCHAR(80) NOT NULL UNIQUE,
    nombre VARCHAR(150) NULL,
    combustible VARCHAR(30) NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
);

ALTER TABLE vehiculo_motor
    ADD COLUMN IF NOT EXISTS familia_motor_id BIGINT NULL;

ALTER TABLE vehiculo_motor
    ADD CONSTRAINT fk_vehiculo_motor_familia
    FOREIGN KEY (familia_motor_id) REFERENCES familia_motor(familia_motor_id);

CREATE INDEX IF NOT EXISTS idx_vehiculo_motor_familia
    ON vehiculo_motor(familia_motor_id);

CREATE TABLE sku_origen (
    sku_id BIGINT PRIMARY KEY REFERENCES sku(sku_id),
    pais_origen_id BIGINT NULL REFERENCES pais(pais_id),
    pais_fabricacion_id BIGINT NULL REFERENCES pais(pais_id),
    fabricante_id BIGINT NULL REFERENCES fabricante(fabricante_id),
    marca_id BIGINT NULL REFERENCES marca(marca_id),
    origen_declarado VARCHAR(150) NULL,
    observacion TEXT NULL
);

CREATE TABLE tipo_repuesto (
    tipo_repuesto_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    descripcion TEXT NULL,
    orden SMALLINT NULL
);

CREATE TABLE nivel_calidad (
    nivel_calidad_id SMALLINT PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT NULL,
    orden_calidad SMALLINT NOT NULL,
    score_referencia NUMERIC(5,2) NULL,
    CONSTRAINT ck_nivel_calidad CHECK (nivel_calidad_id BETWEEN 0 AND 5),
    CONSTRAINT ck_score_referencia CHECK (
        score_referencia IS NULL OR score_referencia BETWEEN 0 AND 100
    )
);

CREATE TABLE sku_clasificacion_calidad (
    sku_id BIGINT PRIMARY KEY REFERENCES sku(sku_id),
    tipo_repuesto_id BIGINT NOT NULL REFERENCES tipo_repuesto(tipo_repuesto_id),
    nivel_calidad_id SMALLINT NOT NULL REFERENCES nivel_calidad(nivel_calidad_id),
    es_original BOOLEAN NOT NULL DEFAULT FALSE,
    es_oem BOOLEAN NOT NULL DEFAULT FALSE,
    es_oe BOOLEAN NOT NULL DEFAULT FALSE,
    es_oes BOOLEAN NOT NULL DEFAULT FALSE,
    es_aftermarket BOOLEAN NOT NULL DEFAULT FALSE,
    es_replica BOOLEAN NOT NULL DEFAULT FALSE,
    es_licenciado BOOLEAN NOT NULL DEFAULT FALSE,
    marca_equivalente_original_id BIGINT NULL REFERENCES marca(marca_id),
    score_calidad NUMERIC(5,2) NULL,
    fuente_calidad VARCHAR(250) NULL,
    fecha_evaluacion DATE NULL,
    observacion TEXT NULL,
    CONSTRAINT ck_score_calidad CHECK (
        score_calidad IS NULL OR score_calidad BETWEEN 0 AND 100
    )
);

CREATE INDEX idx_sku_calidad_nivel
    ON sku_clasificacion_calidad(nivel_calidad_id);
CREATE INDEX idx_sku_calidad_tipo
    ON sku_clasificacion_calidad(tipo_repuesto_id);

CREATE TABLE criterio_calidad (
    criterio_calidad_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(60) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    ponderacion NUMERIC(7,4) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_criterio_ponderacion CHECK (ponderacion >= 0)
);

CREATE TABLE sku_evaluacion_calidad (
    sku_id BIGINT NOT NULL REFERENCES sku(sku_id),
    criterio_calidad_id BIGINT NOT NULL REFERENCES criterio_calidad(criterio_calidad_id),
    valor NUMERIC(6,2) NOT NULL,
    fecha DATE NOT NULL,
    fuente VARCHAR(250) NULL,
    PRIMARY KEY (sku_id, criterio_calidad_id, fecha),
    CONSTRAINT ck_eval_calidad_valor CHECK (valor BETWEEN 0 AND 100)
);

CREATE TABLE sku_vehiculo_marca (
    sku_id BIGINT NOT NULL REFERENCES sku(sku_id),
    vehiculo_marca_id BIGINT NOT NULL REFERENCES vehiculo_marca(vehiculo_marca_id),
    es_principal BOOLEAN NOT NULL DEFAULT FALSE,
    origen_relacion VARCHAR(30) NOT NULL DEFAULT 'FITMENT',
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (sku_id, vehiculo_marca_id)
);

ALTER TABLE referencia_repuesto
    ADD COLUMN IF NOT EXISTS codigo_sin_ceros VARCHAR(120) NULL;

ALTER TABLE referencia_repuesto
    ADD COLUMN IF NOT EXISTS codigo_busqueda VARCHAR(180) NULL;

CREATE INDEX IF NOT EXISTS idx_ref_codigo_busqueda_trgm
    ON referencia_repuesto USING gin (codigo_busqueda gin_trgm_ops);

CREATE TABLE sku_busqueda (
    sku_id BIGINT PRIMARY KEY REFERENCES sku(sku_id),
    texto_busqueda TEXT NOT NULL,
    marcas_vehiculo TEXT NULL,
    modelos_vehiculo TEXT NULL,
    codigos_referencia TEXT NULL,
    marca_repuesto VARCHAR(150) NULL,
    categoria TEXT NULL,
    motores TEXT NULL,
    pais_origen VARCHAR(120) NULL,
    nivel_calidad_id SMALLINT NULL REFERENCES nivel_calidad(nivel_calidad_id),
    search_vector TSVECTOR NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_sku_busqueda_vector
    ON sku_busqueda USING gin(search_vector);
CREATE INDEX idx_sku_busqueda_texto_trgm
    ON sku_busqueda USING gin(texto_busqueda gin_trgm_ops);
CREATE INDEX idx_sku_busqueda_nivel
    ON sku_busqueda(nivel_calidad_id);

